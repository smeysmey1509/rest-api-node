type CategoryCache = Map<string, mongoose.Types.ObjectId>;

type BuildContext = {
  sellerId: mongoose.Types.ObjectId;
  brandId: mongoose.Types.ObjectId;
  profile: BrandProfile;
  globalIndex: number;
  localIndex: number;
  categoryCache: CategoryCache;
  fallbackCategoryId: string;
};

function resolveCategoryId(
  profile: BrandProfile,
  series: string,
  modelVariant: string,
  categoryCache: CategoryCache,
  fallbackCategoryId: string
): mongoose.Types.ObjectId {
  if (profile.categoryRules) {
    for (const rule of profile.categoryRules) {
      if (rule.match.test(series) || rule.match.test(modelVariant)) {
        const cached = categoryCache.get(rule.category.id);
        if (cached) return cached;
      }
    }
  }

  if (profile.defaultCategory) {
    const cached = categoryCache.get(profile.defaultCategory.id);
    if (cached) return cached;
  }

  const fallback = categoryCache.get(fallbackCategoryId);
  if (fallback) return fallback;

  throw new Error(
    `Unable to resolve category for ${profile.brand} ${modelVariant}. Ensure the category exists.`
  );
}

function buildProductPayload({
  sellerId,
  brandId,
  profile,
  globalIndex,
  localIndex,
  categoryCache,
  fallbackCategoryId,
}: BuildContext): Record<string, unknown> {
  const seriesIndex = localIndex % profile.series.length;
  const generation = Math.floor(localIndex / profile.series.length);
  const series = profile.series[seriesIndex];
  const color = profile.colors[(globalIndex + localIndex) % profile.colors.length];
  const storage = profile.storageOptions[(globalIndex + localIndex) % profile.storageOptions.length];
  const display = profile.displaySizes[localIndex % profile.displaySizes.length];
  const chipset = profile.chipsets[(globalIndex + localIndex) % profile.chipsets.length];

  const modelVariant = generation > 0 ? `${series} Gen ${generation + 1}` : series;
  const modelName =
    profile.brand === "Apple" ? modelVariant : `${profile.brand} ${modelVariant}`;
  const slugBase = `${modelName} ${storage}GB ${color}`;
  const slug = slugify(`${slugBase} ${globalIndex + 1}`);

  const categoryId = resolveCategoryId(
    profile,
    series,
    modelVariant,
    categoryCache,
    fallbackCategoryId
  );

  const price = Math.round(
    profile.basePrice +
    generation * profile.priceStep +
    seriesIndex * Math.round(profile.priceStep / 2) +
    Math.random() * profile.priceVariance
  );
  const compareAtPrice = price + Math.round(120 + Math.random() * 160);
  const stock = profile.baseStock + ((localIndex + globalIndex) * 3) % 64;

  const images = [
    `https://cdn.example.com/${profile.slugSegment}/${slug}.jpg`,
    `https://cdn.example.com/${profile.slugSegment}/${slug}-alt.jpg`,
  ];

  const description = `${modelName} delivers flagship experiences with a ${display}-inch ${profile.displayTechnology} display, ${chipset} platform, and ${storage}GB of storage in a ${color.toLowerCase()} finish.`;
  const feature = [
    `• ${display}-inch ${profile.displayTechnology} display`,
    `• ${chipset} 5G processor`,
    `• ${storage}GB storage with high-speed flash`,
    `• ${profile.os}`,
    `• ${profile.charging}`,
  ].join("\n");

  const attributes: Record<string, string> = {
    Brand: profile.brand,
    Series: series,
    Model: modelVariant,
    Storage: `${storage}GB`,
    Color: color,
    Display: `${display}\"`,
    Chipset: chipset,
    OS: profile.os,
  };

  const seoTitle = `${modelName} ${storage}GB ${color} | ${profile.brand} ${profile.productType}`;
  const seoDescription = `${modelName} pairs ${profile.displayTechnology} visuals with ${chipset} performance and ${storage}GB storage for discerning users.`;

  const priceFloor = Math.max(price - 40, Math.round(price * 0.88));
  const storageLabel = `${storage}GB`;
  const variantSkuBase = `${profile.slugSegment}-${modelVariant}-${storageLabel}-${color}-${globalIndex + 1}`;
  const variantSku = variantSkuBase
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64);

  const variants = [
    {
      sku: variantSku,
      price,
      stock,
      inventory: {
        onHand: stock,
        reserved: 0,
        safetyStock: 0,
      },
      attributes: {
        Color: color,
        Storage: storageLabel,
      },
      images,
      isActive: true,
    },
  ];

  return {
    productId: generateProductId(profile.brand, globalIndex),
    name: modelName,
    slug,
    description,
    feature,
    price,
    compareAtPrice,
    currency: "USD",
    stock,
    category: categoryId,
    brand: brandId,
    seller: sellerId,
    status: "Published",
    tag: [
      "phone",
      profile.brand.toLowerCase(),
      profile.slugSegment,
      `${storage}gb`,
      modelVariant.replace(/\s+/g, "-").toLowerCase(),
    ],
    images,
    primaryImageIndex: 0,
    ratingAvg: Math.round((Math.random() * 1.8 + 3.2) * 10) / 10,
    ratingCount: 50 + Math.floor(Math.random() * 250),
    salesCount: 100 + Math.floor(Math.random() * 4000),
    isTrending: profile.brand === "Apple" || profile.brand === "Samsung",
    dimensions: {
      length: Number((16 + Math.random()).toFixed(1)),
      width: Number((7.5 + Math.random() * 0.6).toFixed(1)),
      height: Number((0.75 + Math.random() * 0.2).toFixed(2)),
    },
    weight: Number((185 + Math.random() * 35).toFixed(0)),
    variants,
    attributes,
    seo: {
      title: seoTitle,
      description: seoDescription,
      keywords: [
        profile.brand,
        modelVariant,
        `${profile.brand} smartphone`,
        chipset,
        `${storage}GB phone`,
      ],
    },
    isAdult: false,
    isHazardous: false,
    productType: profile.productType,
    actualPrice: price,
    dealerPrice: Math.round(price * 0.84),
    dedupeKey: `${sellerId.toHexString()}:${slug}`,
    isDeleted: false,
    priceMin: priceFloor,
    priceMax: compareAtPrice,
    cost: Math.round(price * 0.78),
  };
}

type AllocationRuntime = BrandAllocation & { brandId: mongoose.Types.ObjectId };

function buildAllProducts(
  sellerId: mongoose.Types.ObjectId,
  allocations: AllocationRuntime[],
  categoryCache: CategoryCache,
  fallbackCategoryId: string
): Record<string, unknown>[] {
  const products: Record<string, unknown>[] = [];
  let globalIndex = 0;

  for (const allocation of allocations) {
    for (let localIndex = 0; localIndex < allocation.quantity; localIndex += 1) {
      products.push(
        buildProductPayload({
          sellerId,
          profile: allocation.profile,
          brandId: allocation.brandId,
          globalIndex,
          localIndex,
          categoryCache,
          fallbackCategoryId,
        })
      );
      globalIndex += 1;
    }
  }

  return products;
}

async function prepareCategoryCache(
  profiles: BrandProfile[],
  fallbackCategory: CategoryDescriptor
): Promise<CategoryCache> {
  const descriptors = new Map<string, CategoryDescriptor>();
  descriptors.set(fallbackCategory.id, fallbackCategory);

  for (const profile of profiles) {
    if (profile.defaultCategory) {
      descriptors.set(profile.defaultCategory.id, profile.defaultCategory);
    }
    if (profile.categoryRules) {
      for (const rule of profile.categoryRules) {
        descriptors.set(rule.category.id, rule.category);
      }
    }
  }

  const cache: CategoryCache = new Map();
  for (const descriptor of descriptors.values()) {
    const category = await ensureCategory(descriptor.id, descriptor.name);
    cache.set(descriptor.id, category._id as mongoose.Types.ObjectId);
  }

  return cache;
}

async function prepareAllocations(): Promise<AllocationRuntime[]> {
  const allocations: AllocationRuntime[] = [];

  for (const allocation of BRAND_ALLOCATIONS) {
    const brand = await ensureBrand(allocation.profile.brandRecordName, allocation.profile.brandSlug);
    allocations.push({
      ...allocation,
      brandId: brand._id as mongoose.Types.ObjectId,
    });
  }

  return allocations;
}

async function run() {
  const options = buildOptions();
  const mongoUri = process.env.MONGO_URI;
  if (!mongoUri) throw new Error("MONGO_URI environment variable is required");

  console.log(`Connecting to MongoDB...`);
  await mongoose.connect(mongoUri);
  console.log(`Connected. Preparing seed data...`);

  const seller = await User.findById(options.sellerId).select("_id");
  if (!seller) {
    throw new Error(
      `Seller with id ${options.sellerId} was not found. Please create it before seeding.`
    );
  }
  const sellerId = seller._id as mongoose.Types.ObjectId;
  const fallbackCategory: CategoryDescriptor = {
    id: options.categoryId,
    name: options.categoryName,
  };
  const categoryCache = await prepareCategoryCache(
    BRAND_ALLOCATIONS.map((allocation) => allocation.profile),
    fallbackCategory
  );
  const allocations = await prepareAllocations();

  const products = buildAllProducts(sellerId, allocations, categoryCache, fallbackCategory.id);

  const total = products.length;
  console.log("Prepared product distribution:");
  for (const allocation of BRAND_ALLOCATIONS) {
    console.log(`- ${allocation.profile.brand}: ${allocation.quantity}`);
  }
  console.log(`Total products: ${total}`);

  if (options.dryRun) {
    console.log(`Dry run enabled. Generated ${products.length} product payloads.`);
    console.log(products[0]);
    await mongoose.disconnect();
    return;
  }

  const inserted = await Product.insertMany(products, { ordered: false });

  console.log(`Inserted ${inserted.length} products.`);

  await mongoose.disconnect();
  console.log("MongoDB connection closed.");
}

run().catch(async (err) => {
  console.error("Seed script failed:", err);
  try {
    await mongoose.disconnect();
  } catch (disconnectErr) {
    console.error("Failed to disconnect cleanly:", disconnectErr);
  }
  process.exit(1);
});
