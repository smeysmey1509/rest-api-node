type CliOptions = {
  sellerId: string;
  categoryId: string;
  categoryName: string;
  dryRun: boolean;
};

function parseArgs(): Partial<CliOptions> {
  const args = process.argv.slice(2);
  const options: Record<string, string | boolean> = {};

  for (const arg of args) {
    if (!arg.startsWith("--")) continue;
    const [key, rawValue] = arg.slice(2).split("=");
    if (!key) continue;
    if (rawValue === undefined) {
      options[key] = true;
    } else {
      options[key] = rawValue;
    }
  }

  const result: Partial<CliOptions> = {};
  if (typeof options.sellerId === "string") result.sellerId = options.sellerId;
  if (typeof options.categoryId === "string") result.categoryId = options.categoryId;
  if (typeof options.categoryName === "string") result.categoryName = options.categoryName;
  if (typeof options.dryRun === "boolean") result.dryRun = options.dryRun;
  if (typeof options.dryRun === "string") result.dryRun = options.dryRun === "true";

  return result;
}

function slugify(s: string): string {
  return s
    .toLowerCase()
    .trim()
    .replace(/['"]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function escapeRegExp(input: string): string {
  return input.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&");
}

function buildOptions(): CliOptions {
  const parsed = parseArgs();

  return {
    sellerId:
      parsed.sellerId ??
      process.env.SEED_SELLER_ID ??
      "685ab59e33f273e409dc3eac",
    categoryId: parsed.categoryId ?? process.env.SEED_CATEGORY_ID ?? "phones",
    categoryName:
      parsed.categoryName ?? process.env.SEED_CATEGORY_NAME ?? "Smartphones",
    dryRun:
      parsed.dryRun ??
      (typeof process.env.SEED_DRY_RUN === "string"
        ? process.env.SEED_DRY_RUN === "true"
        : false),
  };
}

async function ensureCategory(categoryId: string, categoryName: string) {
  const existing = await Category.findOne({ categoryId }).select("_id");
  if (existing) return existing;

  console.log(`Creating category ${categoryName} (${categoryId})`);
  return Category.create({
    categoryId,
    categoryName,
    description: `${categoryName} autogenerated by seed script`,
  });
}

async function ensureBrand(brandName: string, slug: string) {
  const escapedName = escapeRegExp(brandName);
  const existingByName = await Brand.findOne({
    name: { $regex: new RegExp(`^${escapedName}$`, "i") },
  }).select("_id");
  if (existingByName) return existingByName;

  const escapedSlug = escapeRegExp(slug);
  const existingBySlug = await Brand.findOne({
    slug: { $regex: new RegExp(`^${escapedSlug}$`, "i") },
  }).select("_id");
  if (existingBySlug) return existingBySlug;

  console.log(`Creating brand ${brandName} (${slug})`);
  return Brand.create({ name: brandName, slug, isActive: true });
}

type CategoryDescriptor = {
  id: string;
  name: string;
};

type CategoryRule = {
  match: RegExp;
  category: CategoryDescriptor;
};

